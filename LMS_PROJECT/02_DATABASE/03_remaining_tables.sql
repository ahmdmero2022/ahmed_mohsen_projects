  CONSTRAINT lms_cert_no_uk UNIQUE (certificate_no),
  CONSTRAINT lms_cert_code_uk UNIQUE (verification_code),
  CONSTRAINT lms_cert_user_fk FOREIGN KEY (user_id) REFERENCES lms_users (user_id),
  CONSTRAINT lms_cert_enr_fk FOREIGN KEY (enrollment_id) REFERENCES lms_enrollments (enrollment_id),
  CONSTRAINT lms_cert_pe_fk FOREIGN KEY (path_enrollment_id) REFERENCES lms_path_enrollments (path_enrollment_id),
  CONSTRAINT lms_cert_course_fk FOREIGN KEY (course_id) REFERENCES lms_courses (course_id),
  CONSTRAINT lms_cert_path_fk FOREIGN KEY (path_id) REFERENCES lms_learning_paths (path_id),
  CONSTRAINT lms_cert_tpl_fk FOREIGN KEY (template_id) REFERENCES lms_certificate_templates (template_id),
  CONSTRAINT lms_cert_rev_fk FOREIGN KEY (revoked_by) REFERENCES lms_users (user_id),
  CONSTRAINT lms_cert_status_ck CHECK (status IN ('VALID','REVOKED','EXPIRED','SUPERSEDED')),
  CONSTRAINT lms_cert_src_ck CHECK ((enrollment_id IS NOT NULL AND path_enrollment_id IS NULL AND course_id IS NOT NULL AND path_id IS NULL)
                                 OR (enrollment_id IS NULL AND path_enrollment_id IS NOT NULL AND path_id IS NOT NULL AND course_id IS NULL)),
  CONSTRAINT lms_cert_rev_ck CHECK (status <> 'REVOKED' OR (revoked_at IS NOT NULL AND revoked_reason IS NOT NULL))
);
-- Idempotent issuance (BR-09): one certificate per source enrollment / path enrollment
-- (function-based so rows of the other source type, which hold NULLs, are not indexed)
