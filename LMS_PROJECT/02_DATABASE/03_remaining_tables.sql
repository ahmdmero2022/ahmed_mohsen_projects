-- File metadata. Large video = EXTERNAL (object_key); BLOB only for small documents.
CREATE TABLE lms_lesson_content (
  content_id     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  lesson_id      NUMBER NOT NULL,
  storage_type   VARCHAR2(8) NOT NULL,
  file_name      VARCHAR2(255) NOT NULL,
  mime_type      VARCHAR2(100) NOT NULL,
  file_size      NUMBER(12) NOT NULL,
  checksum_sha256 VARCHAR2(64),
  object_key     VARCHAR2(1000),
  file_blob      BLOB,
  uploaded_by    NUMBER NOT NULL,
  uploaded_at    TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT lms_lc_les_fk FOREIGN KEY (lesson_id) REFERENCES lms_lessons (lesson_id),
  CONSTRAINT lms_lc_user_fk FOREIGN KEY (uploaded_by) REFERENCES lms_users (user_id),
  CONSTRAINT lms_lc_type_ck CHECK (storage_type IN ('EXTERNAL','BLOB')),
  CONSTRAINT lms_lc_size_ck CHECK (file_size >= 0 AND (storage_type = 'EXTERNAL' OR file_size <= 26214400)),
  CONSTRAINT lms_lc_store_ck CHECK ((storage_type = 'EXTERNAL' AND object_key IS NOT NULL AND file_blob IS NULL)
                                 OR (storage_type = 'BLOB' AND file_blob IS NOT NULL))
)
LOB (file_blob) STORE AS SECUREFILE (DISABLE STORAGE IN ROW);
CREATE INDEX lms_lc_les_ix ON lms_lesson_content (lesson_id);
CREATE INDEX lms_lc_user_ix ON lms_lesson_content (uploaded_by);

