  CASE WHEN enrollment_id IS NOT NULL THEN enrollment_id END,
  CASE WHEN enrollment_id IS NOT NULL THEN template_id END);
CREATE UNIQUE INDEX lms_cert_pe_uk ON lms_certificates (
  CASE WHEN path_enrollment_id IS NOT NULL THEN path_enrollment_id END,
  CASE WHEN path_enrollment_id IS NOT NULL THEN template_id END);
