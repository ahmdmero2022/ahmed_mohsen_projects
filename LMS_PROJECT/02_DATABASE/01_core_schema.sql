  CONSTRAINT lms_crs_creator_fk FOREIGN KEY (created_by) REFERENCES lms_users (user_id),
  CONSTRAINT lms_crs_deliv_ck CHECK (delivery_method IN ('SELF_PACED','CLASSROOM','VIRTUAL','BLENDED')),
  CONSTRAINT lms_crs_diff_ck CHECK (difficulty IN ('BEGINNER','INTERMEDIATE','ADVANCED')),
  CONSTRAINT lms_crs_status_ck CHECK (status IN ('DRAFT','UNDER_REVIEW','PUBLISHED','SUSPENDED','ARCHIVED')),
  CONSTRAINT lms_crs_cap_ck CHECK (capacity IS NULL OR capacity > 0),
  CONSTRAINT lms_crs_dates_ck CHECK (available_to IS NULL OR available_from IS NULL OR available_to >= available_from),
  CONSTRAINT lms_crs_dur_ck CHECK (duration_minutes >= 0),
  CONSTRAINT lms_crs_appr_ck CHECK (approval_required IN ('Y','N')),
  CONSTRAINT lms_crs_cert_ck CHECK (certificate_eligible IN ('Y','N')),
  CONSTRAINT lms_crs_feat_ck CHECK (featured_flag IN ('Y','N')),
  CONSTRAINT lms_crs_pass_ck CHECK (pass_score_required IN ('Y','N')),
  CONSTRAINT lms_crs_rule_ck CHECK (completion_rule IN ('LESSONS','LESSONS_ASSESSMENT','ATTENDANCE','LESSONS_ATTENDANCE','INSTRUCTOR_APPROVAL'))
