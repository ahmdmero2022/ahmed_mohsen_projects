-- ---------- Organization ----------------------------------------------------
CREATE TABLE lms_departments (
  department_id        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  department_code      VARCHAR2(30)  NOT NULL,
  name_en              VARCHAR2(200) NOT NULL,
  name_ar              VARCHAR2(200),
  parent_department_id NUMBER,
  active_flag          CHAR(1) DEFAULT 'Y' NOT NULL,
  created_at           TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT lms_dept_code_uk UNIQUE (department_code),
  CONSTRAINT lms_dept_parent_fk FOREIGN KEY (parent_department_id) REFERENCES lms_departments (department_id),
  CONSTRAINT lms_dept_active_ck CHECK (active_flag IN ('Y','N')),
  CONSTRAINT lms_dept_self_ck CHECK (parent_department_id IS NULL OR parent_department_id <> department_id)
);
CREATE INDEX lms_dept_parent_ix ON lms_departments (parent_department_id);

CREATE TABLE lms_positions (
  position_id    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  position_code  VARCHAR2(30)  NOT NULL,
  job_title_en   VARCHAR2(200) NOT NULL,
  job_title_ar   VARCHAR2(200),
  active_flag    CHAR(1) DEFAULT 'Y' NOT NULL,
  CONSTRAINT lms_pos_code_uk UNIQUE (position_code),
  CONSTRAINT lms_pos_active_ck CHECK (active_flag IN ('Y','N'))
);

-- ---------- Identity & RBAC ---------------------------------------------------
CREATE TABLE lms_users (
  user_id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  username         VARCHAR2(100) NOT NULL,           -- stored UPPER(TRIM()), matches APP_USER
  employee_no      VARCHAR2(30)  NOT NULL,
  full_name_en     VARCHAR2(200) NOT NULL,
  full_name_ar     VARCHAR2(200),
  email            VARCHAR2(254) NOT NULL,
  department_id    NUMBER,
  position_id      NUMBER,
  manager_user_id  NUMBER,
  status           VARCHAR2(10) DEFAULT 'ACTIVE' NOT NULL,
  preferred_lang   VARCHAR2(5)  DEFAULT 'en' NOT NULL,
  hired_on         DATE,
  created_at       TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at       TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  row_version      NUMBER DEFAULT 1 NOT NULL,
  CONSTRAINT lms_usr_username_uk UNIQUE (username),
  CONSTRAINT lms_usr_empno_uk UNIQUE (employee_no),
  CONSTRAINT lms_usr_username_ck CHECK (username = UPPER(TRIM(username))),
  CONSTRAINT lms_usr_status_ck CHECK (status IN ('ACTIVE','INACTIVE','LOCKED')),
  CONSTRAINT lms_usr_lang_ck CHECK (preferred_lang IN ('en','ar')),
  CONSTRAINT lms_usr_dept_fk FOREIGN KEY (department_id) REFERENCES lms_departments (department_id),
  CONSTRAINT lms_usr_pos_fk FOREIGN KEY (position_id) REFERENCES lms_positions (position_id),
  CONSTRAINT lms_usr_mgr_fk FOREIGN KEY (manager_user_id) REFERENCES lms_users (user_id),
  CONSTRAINT lms_usr_mgr_self_ck CHECK (manager_user_id IS NULL OR manager_user_id <> user_id)
);
CREATE INDEX lms_usr_dept_ix ON lms_users (department_id);
CREATE INDEX lms_usr_pos_ix  ON lms_users (position_id);
CREATE INDEX lms_usr_mgr_ix  ON lms_users (manager_user_id);

