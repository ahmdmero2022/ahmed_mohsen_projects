  pass_score_required    CHAR(1) DEFAULT 'N' NOT NULL,
  certificate_eligible   CHAR(1) DEFAULT 'N' NOT NULL,
  featured_flag          CHAR(1) DEFAULT 'N' NOT NULL,
  thumbnail_ref          VARCHAR2(500),                  -- object-store key, not a BLOB
  created_by             NUMBER NOT NULL,
