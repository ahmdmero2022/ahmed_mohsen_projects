-- ---------- Settings, audit, security events ---------------------------------------
CREATE TABLE lms_system_settings (
  setting_key    VARCHAR2(60)  PRIMARY KEY,
  setting_value  VARCHAR2(1000) NOT NULL,
  description    VARCHAR2(400),
  updated_at     TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE lms_audit_log (
  audit_id        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  event_time      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  actor_user_id   NUMBER,                              -- no FK: audit must survive user changes
  operation       VARCHAR2(40)  NOT NULL,
  entity_name     VARCHAR2(40)  NOT NULL,
  entity_id       NUMBER,
  result          VARCHAR2(10)  DEFAULT 'SUCCESS' NOT NULL,
  correlation_id  VARCHAR2(64),
  metadata        VARCHAR2(2000),                      -- safe JSON; never secrets/answers
  CONSTRAINT lms_aud_result_ck CHECK (result IN ('SUCCESS','FAILURE','DENIED')),
  CONSTRAINT lms_aud_meta_ck CHECK (metadata IS NULL OR metadata IS JSON)
);
CREATE INDEX lms_aud_time_ix ON lms_audit_log (event_time);
CREATE INDEX lms_aud_entity_ix ON lms_audit_log (entity_name, entity_id, event_time);
CREATE INDEX lms_aud_actor_ix ON lms_audit_log (actor_user_id, event_time);

CREATE TABLE lms_security_events (
  event_id      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  event_time    TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  event_type    VARCHAR2(40) NOT NULL,                 -- RATE_LIMIT, LOGIN_FAIL, ACCESS_DENIED...
  user_id       NUMBER,
  subject_key   VARCHAR2(80),                          -- hashed, never raw IP/session
  operation     VARCHAR2(40),
  severity      VARCHAR2(8) DEFAULT 'INFO' NOT NULL,
  detail        VARCHAR2(1000),
  CONSTRAINT lms_sec_sev_ck CHECK (severity IN ('INFO','WARN','HIGH'))
);
CREATE INDEX lms_sec_time_ix ON lms_security_events (event_time);
CREATE INDEX lms_sec_type_ix ON lms_security_events (event_type, event_time);

-- ---------- Rate limiting ------------------------------------------------------------
CREATE TABLE lms_rate_limit_policies (
  policy_id       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  operation_name  VARCHAR2(40) NOT NULL,
  limit_count     NUMBER(8)  NOT NULL,
  window_seconds  NUMBER(8)  NOT NULL,
  burst_limit     NUMBER(8),                           -- optional hard cap per 10 s
  fail_mode       VARCHAR2(6) DEFAULT 'OPEN' NOT NULL, -- behaviour if limiter itself errors
  enabled_flag    CHAR(1) DEFAULT 'Y' NOT NULL,
  created_at      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT lms_rlp_op_uk UNIQUE (operation_name),
  CONSTRAINT lms_rlp_cnt_ck CHECK (limit_count > 0),
  CONSTRAINT lms_rlp_win_ck CHECK (window_seconds BETWEEN 1 AND 86400),
  CONSTRAINT lms_rlp_fail_ck CHECK (fail_mode IN ('OPEN','CLOSED')),
  CONSTRAINT lms_rlp_en_ck CHECK (enabled_flag IN ('Y','N'))
);

CREATE TABLE lms_rate_limit_counters (
  counter_id     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  policy_id      NUMBER NOT NULL,
  subject_key    VARCHAR2(80) NOT NULL,
  window_start   NUMBER(12) NOT NULL,                  -- epoch seconds, aligned to window
  request_count  NUMBER(8) DEFAULT 0 NOT NULL,
  expires_at     TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT lms_rlc_policy_fk FOREIGN KEY (policy_id) REFERENCES lms_rate_limit_policies (policy_id),
  CONSTRAINT lms_rlc_uk UNIQUE (policy_id, subject_key, window_start)
);
CREATE INDEX lms_rlc_exp_ix ON lms_rate_limit_counters (expires_at);
