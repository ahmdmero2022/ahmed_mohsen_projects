  course_id              NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  course_code            VARCHAR2(30)  NOT NULL,
  title_en               VARCHAR2(250) NOT NULL,
  title_ar               VARCHAR2(250),
  description_en         CLOB,
  description_ar         CLOB,
  category_id            NUMBER NOT NULL,
  delivery_method        VARCHAR2(15) NOT NULL,
  difficulty             VARCHAR2(12) DEFAULT 'BEGINNER' NOT NULL,
  duration_minutes       NUMBER(6) DEFAULT 0 NOT NULL,
  language_code          VARCHAR2(5) DEFAULT 'en' NOT NULL,
